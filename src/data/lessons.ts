export function getLesson(courseSlug: string, lessonSlug: string) {
  const course = getCourse(courseSlug)
  if (!course) return undefined
  return LESSONS.find((lesson) => lesson.courseId === course.id && lesson.slug === lessonSlug)
}

export function getLessonById(id: string) {
  return LESSONS.find((lesson) => lesson.id === id)
}

export function getCourseLessons(courseId: string) {
  return LESSONS.filter((lesson) => lesson.courseId === courseId).sort((a, b) => a.number - b.number)
}

export function getAdjacentLessons(lesson: Lesson) {
  const list = getCourseLessons(lesson.courseId)
  const index = list.findIndex((item) => item.id === lesson.id)
  return { prev: list[index - 1], next: list[index + 1], course: COURSES.find((c) => c.id === lesson.courseId) }
}
