import { COURSES } from '@/data/catalog'
import type { Lesson } from '@/types'

type Spec = {
  id: string
  slug: string
  courseId: string
  number: number
  title: string
  description: string
  difficulty: Lesson['difficulty']
  estimatedMinutes: number
  keywords: string[]
  explanation: string
  exampleTitle: string
  exampleBody: string
  exampleCode: string
  tip: string
  mistake: string
  practice: string
  practiceCode: string
}

function fromSpec(spec: Spec, extra?: Lesson['sections']): Lesson {
  return {
    id: spec.id,
    slug: spec.slug,
    courseId: spec.courseId,
    number: spec.number,
    title: spec.title,
    description: spec.description,
    difficulty: spec.difficulty,
    estimatedMinutes: spec.estimatedMinutes,
    keywords: spec.keywords,
    exerciseIds: [`ex-${spec.id}`],
    sections: [
      { id: `${spec.id}-intro`, title: 'Explanation', type: 'text', body: spec.explanation },
      {
        id: `${spec.id}-example`,
        title: spec.exampleTitle,
        type: 'example',
        body: spec.exampleBody,
        code: spec.exampleCode,
      },
      ...(extra ?? []),
      { id: `${spec.id}-tip`, title: 'Tip', type: 'tip', body: spec.tip },
      { id: `${spec.id}-mistake`, title: 'Common mistake', type: 'mistake', body: spec.mistake },
      {
        id: `${spec.id}-practice`,
        title: 'Practice',
        type: 'practice',
        body: spec.practice,
        code: spec.practiceCode,
      },
    ],
  }
}

